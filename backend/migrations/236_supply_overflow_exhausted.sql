-- APEXONE-EXT: 双边市场——兜底池也耗尽的日计数。
--
-- 迁移 227 建这张表时数了两件事：溢出了几次（overflow_count，平台在花钱供货）、
-- 被日配额拦下几次（denied_count，平台在省钱）。它们回答的都是「溢出这条路上
-- 发生了什么」。
--
-- 缺的是第三件、也是唯一一件**用户能感觉到**的事：溢出了，可兜底池自己也空了，
-- 于是消费者拿到 "No available accounts"。这一列存在的理由：
--
--   1. **它是「该不该加兜底账号」的唯一信号。** 兜底池是保险，保险的尺寸由
--      「盖不住的次数」决定，而不是由它平时用了多少决定。此前这个数只在一条
--      Error 日志里，要靠翻日志估——而一个只能靠翻日志回答的问题，
--      实际上没人会去回答。
--   2. **它与另外两个数的含义正交，不能合并。** overflow_count 是「保险生效了」，
--      denied_count 是「保险被预算挡住了」，exhausted_count 是「保险不够赔」。
--      三者对应三种完全不同的处置：什么都不做 / 调预算 / 加账号。
--      合成一个数字之后，这三条路就分不出来了。
--
-- 不新建表而是加一列：同一个日桶、同一次 upsert 的形状、同一套清理策略。
-- 为它单独建表会让「今天供给侧发生了什么」需要 join 两张表才答得出来。
--
-- 默认 0 且 NOT NULL：存量行补零是对的——那些天没有这个计数，不是「未知」，
-- 而是「当时没在数」。对读侧来说两者都该显示 0，而 NULL 会让求和悄悄变成 NULL。

ALTER TABLE supply_overflow_daily
    ADD COLUMN IF NOT EXISTS exhausted_count BIGINT NOT NULL DEFAULT 0;

COMMENT ON COLUMN supply_overflow_daily.exhausted_count IS
    '溢出到兜底池后兜底池也耗尽的次数——消费者真正看到"无可用账号"的那一刻；加兜底账号的唯一依据';
