-- APEXONE-EXT: 双边市场——授权会话记住"这一次是为哪个号"。
--
-- 迁移 226 建这张表时，会话只有一种用途：换一个**新**账号。所以它不需要知道
-- 自己指向谁——兑换的产物就是那个号本身。
--
-- 现在多了第二种用途：**就地重新授权**一个已经存在的号（凭证过期了，供给者要
-- 换一份新的进去，而账号 id、每日上限、已产生的收益、观察期进度都得留着）。
-- 这一种必须知道自己指向谁。
--
-- 为什么加一列而不是新建一张 supplier_reauth_sessions：
--
--   1. **两种会话的生命周期一模一样。** 15 分钟 TTL、一次性领取（UPDATE ...
--      RETURNING 的原子消费）、每人未消费条数上限、过期清理。新建一张表要把
--      这四样各抄一遍，而它们是这张表全部的复杂度所在——抄一遍就是留一份将来
--      会漂移的副本。
--   2. **「这个人手上有几条待兑换的授权」是一个跨两种用途的问题。** 每条会话
--      都对应一次上游授权页跳转，上限拦的是那个，与它兑换出来的是新号还是旧号
--      无关。分成两张表之后这道闸就得查两次再相加，而漏掉一边不会报错。
--
-- 为什么可空而不是给接入会话填一个哨兵值（比如 0）：
--
--   NULL 在这里有确切含义——"没有指向任何账号"，而 0 是一个不存在的账号 id，
--   要靠读代码的人记住这条约定。领取语句用 `IS NOT DISTINCT FROM` 比对，
--   NULL 与 NULL 相等、NULL 与任何数不等，两类会话因此**在同一条原子 UPDATE 里**
--   互不通兑：一条为账号 N 发起的会话换不出一个新号，一条接入会话也修不了 N。
--   把这个判断放进 SQL 而不是领取之后再校验，是因为后者是一句可以被重构删掉的
--   if，而前者删掉就没有行返回。
--
-- ON DELETE CASCADE：账号行被硬删时，指向它的待兑换会话没有任何意义。
-- 本仓的账号删除是软删（deleted_at），所以这条级联实际上只在运维硬删时触发——
-- 它存在是为了不留悬挂引用，不是一条会被日常走到的路径。
--
-- 不加索引：这张表的每一次读都从 session_id 的唯一索引进去（领取、计数除外，
-- 后者走 user_id）。account_id 只是已经定位到行之后的一个等值过滤，
-- 为它建索引只会让每次插入多维护一棵树。

ALTER TABLE supplier_oauth_sessions
    ADD COLUMN IF NOT EXISTS account_id BIGINT NULL REFERENCES accounts(id) ON DELETE CASCADE;

COMMENT ON COLUMN supplier_oauth_sessions.account_id IS
    'NULL = 接入会话（兑换出一个新号）；非 NULL = 就地重新授权那一个号。领取时进 WHERE，两类会话互不通兑。';
